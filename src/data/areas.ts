export function visitPolicyText(a: Area) {
  if (a.slug === "gyeongbuk") return "경북 전역 당일 출장 원칙";
  return a.policy === "same-day"
    ? `대구에서 차로 약 ${a.driveMin}분, 당일 출장 원칙`
    : `대구에서 차로 약 ${a.driveMin}분, 일정을 잡아 방문`;
}

